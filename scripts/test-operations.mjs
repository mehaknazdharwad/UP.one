import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const moduleURL=source=>'data:text/javascript;base64,'+Buffer.from(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString('base64');
const domainURL=moduleURL(fs.readFileSync('lib/domain.ts','utf8'));
const domain=await import(domainURL);
const op=await import(moduleURL(fs.readFileSync('lib/operations.ts','utf8').replace("'./domain'",JSON.stringify(domainURL))));
const {translator}=await import(moduleURL(fs.readFileSync('lib/i18n.ts','utf8')));
const now=Date.now(),base=domain.seed(),c={...base[0],status:'In progress',createdAt:new Date(now-7*op.DAY).toISOString()};
assert.equal(base.length,15);assert.equal(new Set(base.map(c=>c.status)).size,7);
assert.equal(op.slaState(c,now),'overdue');assert.equal(op.slaState(c,now-1),'near');
assert.equal(op.slaState({...c,createdAt:new Date(now-5*op.DAY).toISOString()},now),'near');
assert.equal(op.slaState({...c,status:'Closed',resolvedAt:null},now),'unknown');
assert.equal(op.matchesRisk({...c,status:'Closed'},'overdue',now),false);
assert.equal(op.matchesRisk({...c,status:'Escalated'},'escalation',now),false);
assert.equal(op.matchesRisk(c,'escalation',now),true);
const m=op.metrics(base,now);assert.equal(m.active+m.completed,m.total);assert.equal(m.total,15);
for(const risk of ['overdue','near','critical','escalated','unassigned','escalation'])assert.equal(op.selectComplaints(base,{...op.emptyFilters,risk},now).length,m[risk]);
assert.equal(domain.recurringGroups(base).flat().length,12);
assert.equal(op.selectComplaints(base,{...op.emptyFilters,recurrence:'Power outage'},now).length,3);
assert.equal(op.cohort(base,{...op.emptyFilters,query:'बिजली कटौती'},now,translator('hi')).length,4);
assert.equal(translator('hi')('Unknown'),'अज्ञात');assert.equal(translator('en')('Error / त्रुटि'),'Error');assert.equal(translator('hi')('Error / त्रुटि'),'त्रुटि');
const reopened={...c,resolvedAt:null,status:'Reopened',history:[{at:new Date(now-op.DAY).toISOString(),action:'Resolved',note:'Repaired'}]};
assert.equal(op.trendBins([reopened],now).reduce((n,b)=>n+b.resolved,0),1);
reopened.history.push({at:new Date(now-op.DAY).toISOString(),action:'Resolved',fromStatus:'Resolved',note:'Verification note'});
assert.equal(op.trendBins([reopened],now).reduce((n,b)=>n+b.resolved,0),1);
console.log('PASS: 15 samples, SLA boundaries, unknown resolution dates, consistent risk counts, recurring drilldowns, Hindi search, bilingual errors and reopened resolution history.');
